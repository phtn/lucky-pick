import Papa from 'papaparse'
import { RESULT_GAMES, type ResultGame, type ResultGameId } from '../src/lib/results'
import { parseResultDate, RESULT_TIMES } from '../src/lib/results-normalize'
import { parseRawResults, type RawResults } from '../src/lib/results-import'

export interface CsvImportChange { game: ResultGameId; added: number; before: string; after: string }
export interface CsvImportPlan { parsed: RawResults; added: number; skipped: number; changes: CsvImportChange[] }

/** Keep identities even when another field is invalid; never overwrite source rows. */
export function inspectResultCsv(text: string, game: ResultGame) {
  const bom = text.startsWith('\uFEFF') ? '\uFEFF' : ''
  const source = text.slice(bom.length)
  const expected = game.timed ? ['game', 'time', 'numbers', 'date', 'jackpot', 'winners'] : ['game', 'numbers', 'date', 'jackpot', 'winners']
  let header: string[] | undefined, headerEnd = 0
  const ids = new Set<string>()
  Papa.parse<string[]>(source, {
    delimiter: ',', skipEmptyLines: false, dynamicTyping: false,
    step(result) {
      const cells = result.data.map(cell => cell.trim())
      if (cells.every(cell => !cell)) return
      if (!header) {
        if (result.errors.length || cells.length !== expected.length || new Set(cells).size !== cells.length || expected.some(field => !cells.includes(field))) throw new Error(`${game.id}.csv: invalid CSV header.`)
        header = cells
        headerEnd = result.meta.cursor
        return
      }
      const row = Object.fromEntries(header.map((field, index) => [field, cells[index] ?? '']))
      try {
        const date = parseResultDate(row.date)
        const time = game.timed ? row.time : 'daily'
        if (game.timed && !RESULT_TIMES.includes(time as typeof RESULT_TIMES[number])) return
        ids.add(`${game.id}:${date}:${time}`)
      } catch { /* Unrecognizable source rows stay untouched. */ }
    },
  })
  if (!header) throw new Error(`${game.id}.csv: missing CSV header.`)
  return { ids, header, headerEnd, source, bom, newline: source.includes('\r\n') ? '\r\n' : '\n' }
}

export function planCsvImport(text: string, sources: Record<ResultGameId, string>): CsvImportPlan {
  const parsed = parseRawResults(text)
  if (!parsed.sourceRows) throw new Error('No result rows found. Paste or add results to raw.txt first.')
  if (parsed.issues.length) throw new Error(parsed.issues.map(issue => `Line ${issue.line}: ${issue.message}`).join('\n'))
  let added = 0, skipped = parsed.duplicateRows
  const changes = RESULT_GAMES.map(game => {
    const before = sources[game.id]
    const csv = inspectResultCsv(before, game)
    const fresh = parsed.records.filter(item => item.game === game.id && !csv.ids.has(item.record.id))
    skipped += parsed.records.filter(item => item.game === game.id && csv.ids.has(item.record.id)).length
    fresh.sort((a, b) => b.record.date.localeCompare(a.record.date) || RESULT_TIMES.indexOf(b.record.time!) - RESULT_TIMES.indexOf(a.record.time!))
    added += fresh.length
    if (!fresh.length) return { game: game.id, added: 0, before, after: before }
    const rows = fresh.map(({ record }) => {
      const [year, month, day] = record.date.split('-')
      const row: Record<string, string> = { game: game.label, time: record.time ?? '', numbers: record.rawNumbers!, date: `${Number(month)}/${Number(day)}/${year}`, jackpot: `${Math.floor(record.jackpotCents / 100)}.${String(record.jackpotCents % 100).padStart(2, '0')}`, winners: record.winners === null ? '' : String(record.winners) }
      return csv.header.map(field => row[field]!)
    })
    const prefix = csv.source.slice(0, csv.headerEnd)
    const after = csv.bom + prefix + (/[\r\n]$/.test(prefix) ? '' : csv.newline)
      + Papa.unparse(rows, { newline: csv.newline, header: false }) + csv.newline + csv.source.slice(csv.headerEnd)
    return { game: game.id, added: fresh.length, before, after }
  })
  return { parsed, added, skipped, changes }
}

export function buildCsvBaseline(sources: Record<ResultGameId, string>): string {
  const dates: Record<string, string> = {}
  for (const game of RESULT_GAMES) {
    const byDate = new Map<string, number>()
    for (const id of inspectResultCsv(sources[game.id], game).ids) {
      const [, date, time] = id.split(':')
      byDate.set(date!, (byDate.get(date!) ?? 0) | (game.timed ? 1 << RESULT_TIMES.indexOf(time as typeof RESULT_TIMES[number]) : 0))
    }
    dates[game.id] = [...byDate.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([date, mask]) => mask ? `${date}:${mask}` : date).join(' ')
  }
  return `// Generated by bun run results:build from CSV draw identities. Do not edit.\nconst dates: Record<string, string> = ${JSON.stringify(dates, null, 2)}\nexport const CSV_DRAW_IDS: readonly string[] = Object.entries(dates).flatMap(([game, encoded]) => encoded.split(' ').filter(Boolean).flatMap(value => {\n  const [date, mask] = value.split(':')\n  return mask ? ['2PM', '5PM', '9PM'].filter((_, index) => Number(mask) & (1 << index)).map(time => game + ':' + date + ':' + time) : [game + ':' + date + ':daily']\n}))\n`
}
